const assert=require('node:assert/strict');
const {words,decide}=require('../static/logic.js');
const policy={overall:80,phone:70,focus:'ʌ',require:true};
const run={request:{coreType:'word.eval.promax',scale:100},response:{eof:1,result:{overall:90,words:[{word:'monkey',phonemes:[{phoneme:'ʌ',pronunciation:40,readType:6,sound_like:'uː'}]}]}}};
assert.equal(decide(run,policy).status,'retry');
run.response.result.words[0].phonemes[0]={phoneme:'ʌ',pronunciation:90,readType:0};
assert.equal(decide(run,policy).status,'pass');
run.request.scale=5;run.response.result.overall=4.5;run.response.result.words[0].phonemes[0].pronunciation=4.5;
assert.equal(decide(run,policy).status,'pass');
assert.equal(decide(run,{...policy,focus:'AE'}).status,'review');
run.response.result.warning=[{code:1004,message:'Audio noisy!'}];
assert.equal(decide(run,policy).status,'review');delete run.response.result.warning;
run.response.eof=0;assert.equal(decide(run,policy).status,'review');run.response.eof=1;
run.request.coreType='asr.eval';assert.equal(decide(run,policy).status,'review');
assert.deepEqual(words({sentences:[{details:[{word:'Hello',overall:80}]}]}),[{word:'Hello',overall:80}]);
run.request.coreType='para.eval';run.response.result={overall:4.5,sentences:[{details:[{word:'Hello',overall:4}]}]};
assert.equal(decide(run,{...policy,focus:'',require:false}).status,'pass');
assert.equal(decide(run,policy).status,'review');
